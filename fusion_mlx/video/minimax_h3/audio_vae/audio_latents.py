def _as_param(vec):
    # (32,) → (1, 1, 32) 广播到 (B, T, 32)。
    return mx.array(vec, dtype=mx.float32).reshape(1, 1, -1)


def normalize_audio_latents(latents):
    # latents (B, T, 32) → (x - mean) / std。DiT 输入归一化。
    mean = _as_param(LATENTS_MEAN)
    std = _as_param(LATENTS_STD)
    return (latents - mean) / std


def denormalize_audio_latents(latents):
    # latents (B, T, 32) → x * std + mean。decode 前反归一化。
    mean = _as_param(LATENTS_MEAN)
    std = _as_param(LATENTS_STD)
    return latents * std + mean


